#!/usr/bin/env node
// Step 0 of the Strata asset pipeline (STRATA_SPEC.md B2): extract the Kenney zips in assets/source/ (if not extracted yet), list every PNG of the Voxel Pack
// (name, size, subfolder, alpha) and every audio file of the sound packs (name, duration, format), list the fonts, and write STRATA_ASSET_MANIFEST.md.
// Needs `unzip` and `ffprobe` on the PATH (dev-only; nothing here ships). Nothing is built or chosen here: the role picks live in tools/strata/assets.json.
//   node tools/strata/inventory-assets.mjs [--src assets/source] [--out STRATA_ASSET_MANIFEST.md]
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname, basename, relative, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const SRC = resolve(ROOT, arg('--src', 'assets/source'));
const OUT = resolve(ROOT, arg('--out', 'STRATA_ASSET_MANIFEST.md'));

// ---- 1. extract
const zips = readdirSync(SRC).filter((f) => f.endsWith('.zip')).sort();
const extracted = [];
for (const z of zips) {
  const dir = join(SRC, basename(z, '.zip'));
  if (existsSync(dir) && readdirSync(dir).length) continue;
  mkdirSync(dir, { recursive: true });
  execFileSync('unzip', ['-oq', join(SRC, z), '-d', dir]);
  extracted.push(basename(dir));
}
console.log(extracted.length ? `extracted: ${extracted.join(', ')}` : 'all zips were already extracted');

const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])).sort();

// ---- 2. PNGs of the voxel pack (IHDR: width, height, colour type; alpha = colour type 4 or 6, or a tRNS chunk)
function pngInfo(file) {
  const b = readFileSync(file);
  const w = b.readUInt32BE(16), h = b.readUInt32BE(20), ct = b[25];
  return { w, h, alpha: ct === 4 || ct === 6 || b.includes(Buffer.from('tRNS')), bytes: b.length };
}
const voxel = join(SRC, 'kenney_voxel-pack');
const pngs = existsSync(voxel) ? walk(join(voxel, 'PNG')).filter((f) => f.endsWith('.png')).map((f) => ({ rel: relative(join(voxel, 'PNG'), f), ...pngInfo(f) })) : [];

// ---- 3. audio (ffprobe)
function audioInfo(file) {
  const j = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-print_format', 'json', '-show_format', '-show_streams', file], { encoding: 'utf8' }));
  const s = j.streams.find((x) => x.codec_type === 'audio') ?? {};
  return { dur: Number(j.format.duration ?? 0), codec: s.codec_name, ch: s.channels, rate: Number(s.sample_rate), bytes: Number(j.format.size ?? statSync(file).size) };
}
const soundPacks = ['kenney_impact-sounds', 'kenney_rpg-audio', 'kenney_interface-sounds', 'kenney_ui-audio', 'kenney_music-jingles'];
const audio = soundPacks.filter((p) => existsSync(join(SRC, p))).map((p) => ({
  pack: p,
  files: walk(join(SRC, p)).filter((f) => ['.ogg', '.wav', '.mp3'].includes(extname(f))).filter((f) => basename(f) !== 'Preview.ogg').map((f) => ({ rel: relative(join(SRC, p), f), ...audioInfo(f) })),
}));

// ---- 4. fonts
const fontDir = join(SRC, 'kenney_kenney-fonts');
const fonts = existsSync(fontDir) ? walk(fontDir).filter((f) => /\.(ttf|otf)$/i.test(f)).map((f) => ({ rel: relative(fontDir, f), bytes: statSync(f).size })) : [];

// ---- 5. write the manifest
const kb = (n) => (n / 1024).toFixed(1);
const out = [];
out.push('# STRATA_ASSET_MANIFEST.md\n');
out.push('Generated by `tools/strata/inventory-assets.mjs` (Step 0 of STRATA_SPEC.md). Raw packs live in `assets/source/` (gitignored); nothing here is built or committed as an asset.\n');
const bySub = {};
for (const p of pngs) (bySub[p.rel.split('/')[0]] ??= []).push(p);
out.push(`## Voxel Pack PNGs: ${pngs.length} files\n`);
out.push('| Folder | Files | Sizes | With alpha |\n|---|---|---|---|');
for (const [k, v] of Object.entries(bySub)) out.push(`| ${k} | ${v.length} | ${[...new Set(v.map((p) => `${p.w}x${p.h}`))].join(', ')} | ${v.filter((p) => p.alpha).length} |`);
out.push('');
for (const [k, v] of Object.entries(bySub)) {
  out.push(`### ${k}\n`);
  out.push('| File | Size | Alpha | KB |\n|---|---|---|---|');
  for (const p of v) out.push(`| ${p.rel.slice(k.length + 1)} | ${p.w}x${p.h} | ${p.alpha ? 'yes' : ''} | ${kb(p.bytes)} |`);
  out.push('');
}
out.push(`## Audio: ${audio.reduce((n, p) => n + p.files.length, 0)} files in ${audio.length} packs\n`);
for (const p of audio) {
  const total = p.files.reduce((n, f) => n + f.bytes, 0);
  out.push(`### ${p.pack} (${p.files.length} files, ${(total / 1048576).toFixed(2)} MB)\n`);
  out.push('| File | Duration | Format | Channels | Rate | KB |\n|---|---|---|---|---|---|');
  for (const f of p.files) out.push(`| ${f.rel} | ${f.dur.toFixed(2)} s | ${f.codec} | ${f.ch} | ${f.rate} | ${kb(f.bytes)} |`);
  out.push('');
}
out.push(`## Fonts: ${fonts.length} files\n`);
out.push('| File | KB |\n|---|---|');
for (const f of fonts) out.push(`| ${f.rel} | ${kb(f.bytes)} |`);
out.push('');
writeFileSync(OUT, out.join('\n'));
console.log(`${relative(ROOT, OUT)}: ${pngs.length} PNGs, ${audio.reduce((n, p) => n + p.files.length, 0)} audio files, ${fonts.length} fonts`);
